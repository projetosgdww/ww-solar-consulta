'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync('cliente-dev.html','utf8');
const admin=fs.readFileSync('admin-dev.html','utf8');
const build=fs.readFileSync('scripts/build-cliente-dev.mjs','utf8');
const official='release/wwsolar-pecas-v1';
const preview='feat/wwsolar-seo-local-caninde-paramoti-caridade-dev-20261117';

test('SEO público contém título, descrição e cidades atendidas sem prometer instalação',()=>{
 assert.match(html,/<meta name="robots" content="noindex,nofollow">/);
 assert.match(html,/<meta name="description" content="[^"]+"/);
 assert.match(html,/<title>[^<]*Ceará: Canindé, Paramoti e Caridade<\/title>/);
 assert.match(html,/<link rel="canonical" href="https:\/\/catalogo\.wwplatform\.com\.br\/">/);
 assert.match(html,/Consultas de kits solares em Canindé, Paramoti, Caridade e demais cidades do Ceará/);
 assert.match(html,/frete sujeitos à confirmação/);
 assert.match(html,/<meta property="og:title"/);
 assert.match(html,/<meta name="twitter:card"/);
 const ld=html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
 assert.ok(ld);
 const data=JSON.parse(ld[1]);
 assert.equal(data['@context'],'https://schema.org');
 const organization=data['@graph'].find(x=>x['@type']==='Organization');
 assert.ok(organization);
 assert.deepEqual(organization.areaServed.map(x=>x.name),['Ceará','Canindé','Paramoti','Caridade']);
 assert.equal(organization.telephone,'+55 85 99272-3637');
});
test('preview mantém bloqueio completo e release libera somente página pública',async()=>{
 const policy=await import('../scripts/seo-output-policy.mjs');
 const published=policy.publicCatalogHtml(html,official);
 const testPreview=policy.publicCatalogHtml(html,preview);
 assert.match(published,/<meta name="robots" content="index,follow">/);
 assert.doesNotMatch(published,/<meta name="robots" content="noindex,nofollow">/);
 assert.match(testPreview,/<meta name="robots" content="noindex,nofollow">/);
 assert.doesNotMatch(testPreview,/<meta name="robots" content="index,follow">/);
 assert.match(admin,/<meta name="robots" content="noindex,nofollow">/);
 assert.throws(()=>policy.publicCatalogHtml(html.replace('noindex,nofollow','index,follow'),official),/Meta robots/);
 assert.throws(()=>policy.publicCatalogHtml(html.replace('rel="canonical"','rel="alternate"'),official),/Canonical/);
 assert.equal(policy.isOfficialSeoRelease(''),false);
 assert.equal(policy.isOfficialSeoRelease('main'),false);
 assert.equal(policy.isOfficialSeoRelease(official),true);
});
test('noindex em todos os pages.dev e painel, sem bloqueio global na release',async()=>{
 const policy=await import('../scripts/seo-output-policy.mjs');
 const prod=policy.seoHeaders(official);
 const dev=policy.seoHeaders(preview);
 assert.ok(prod.includes('https://ww-solar.pages.dev/*'));
 assert.ok(prod.includes('https://:version.ww-solar.pages.dev/*'));
 assert.ok(prod.includes('/admin.html\n  X-Robots-Tag: noindex, nofollow'));
 assert.ok(prod.includes('/cliente-dev.html\n  X-Robots-Tag: noindex, nofollow'));
 assert.ok(!prod.includes('/*\n  X-Robots-Tag: noindex, nofollow'));
 assert.ok(dev.includes('/*\n  X-Robots-Tag: noindex, nofollow'));
 assert.match(prod,/X-Content-Type-Options: nosniff/);
 assert.match(prod,/Cache-Control: no-store/);
});
test('sitemap somente na release, aponta canônico público sem incluir admin',async()=>{
 const policy=await import('../scripts/seo-output-policy.mjs');
 const files=policy.seoDiscoveryFiles(official);
 assert.equal(Object.keys(policy.seoDiscoveryFiles(preview)).length,0);
 assert.ok(files['robots.txt'].includes('Sitemap: https://catalogo.wwplatform.com.br/sitemap.xml'));
 assert.match(files['sitemap.xml'],/<loc>https:\/\/catalogo\.wwplatform\.com\.br\/<\/loc>/);
 assert.doesNotMatch(files['sitemap.xml'],/admin|cliente-dev|preview/);
 assert.match(build,/seoDiscoveryFiles\(branch\)/);
 assert.match(build,/publicCatalogHtml\(sourceCustomer,branch\)/);
 assert.match(build,/seoHeaders\(branch\)/);
 assert.ok(build.includes("if(process.env.CF_PAGES_BRANCH==='feat/vitrine-publica-controlada-v1')"));
});
